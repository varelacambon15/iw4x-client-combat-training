#!/usr/bin/env python3
"""
Advanced Combat Training: builds the Supply Drops menus.

The sources (advanced_combat_training/menu_src/ui_mp/*.menu) use big macros (a weapon card is dozens of items). The
game's menu parser expands a macro in one go in its small, fixed hunk memory, and these ran it out of memory
("Hunk_AllocLowAlign failed"). So the menus are expanded here, once, and the mod ships them already expanded:
the game then just reads them item by item.

    python3 tools/build_sd_menus.py <IW4x rawfiles folder (the one with ui/menudef.h)>

Needs cpp (the C preprocessor). Writes advanced_combat_training/mod/ui_mp/<name>.menu for every source menu.

It also builds what the Weapons Store needs from advanced_combat_training/mod/supply_drops/weapons.txt: the STORE
WEAPONS popup of Create a Class (ui_mp/popup_cac_store_primary.menu), and IW4x's mp/statstable.csv and
mp/unlocktable.csv with a row for each store weapon (its name, picture and stats; unlocked from the start, the store
decides who has it).
"""

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "advanced_combat_training" / "menu_src"
OUT = ROOT / "advanced_combat_training" / "mod" / "ui_mp"

HEADER = "// Generated by tools/build_sd_menus.py from advanced_combat_training/menu_src/ui_mp/{name}: edit that file instead.\n"


def merge_strings(text: str) -> str:
    # "sd_rv0" + "_name" -> "sd_rv0_name" (the sources build dvar names from a card's prefix)
    pattern = re.compile(r'"((?:[^"\\]|\\.)*)"\s*\+\s*"((?:[^"\\]|\\.)*)"')
    while True:
        merged = pattern.sub(lambda m: '"' + m.group(1) + m.group(2) + '"', text)
        if merged == text:
            return text
        text = merged


def tidy(text: str) -> str:
    text = re.sub(r"[ \t]+", " ", text)
    # one statement block per line is plenty; keep the file readable-ish and the lines short
    text = text.replace(" itemDef {", "\nitemDef {")
    text = re.sub(r"\n\s*\n+", "\n", text)
    return text.strip() + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 1

    rawfiles = pathlib.Path(sys.argv[1])
    if not (rawfiles / "ui" / "menudef.h").exists():
        print(f"{rawfiles} has no ui/menudef.h")
        return 1

    for source in sorted((SRC / "ui_mp").glob("*.menu")):
        result = subprocess.run(
            ["cpp", "-P", "-undef", "-nostdinc", "-x", "c", "-I", str(SRC), "-I", str(rawfiles), str(source)],
            capture_output=True, text=True,
        )
        errors = [line for line in result.stderr.splitlines() if "error" in line]
        if result.returncode != 0 or errors:
            print(result.stderr)
            return 1

        text = tidy(merge_strings(result.stdout))
        target = OUT / source.name
        target.write_text(HEADER.format(name=source.name) + text, newline="\n")

        tokens = len(re.findall(r'"[^"]*"|[A-Za-z_][A-Za-z_0-9]*|\d+\.?\d*|[^\s\w"]', text))
        print(f"{source.name}: {text.count('itemDef')} items, {tokens} tokens")

    build_store(rawfiles)
    return 0


CATEGORY_CLASS = {
    "assault": "weapon_assault", "smg": "weapon_smg", "lmg": "weapon_lmg", "sniper": "weapon_sniper",
    "shotgun": "weapon_shotgun", "mpistol": "weapon_machine_pistol", "pistol": "weapon_pistol",
}
CATEGORY_DESC = {
    "assault": "PERKS_AR_FULLAUTO", "smg": "PERKS_SMG", "lmg": "PERKS_LMG", "sniper": "PERKS_SNIPER_BOLT",
    "shotgun": "PERKS_SHOTGUN_PUMP", "mpistol": "PERKS_MPISTOL_FULLAUTO", "pistol": "PERKS_PISTOL_SEMIAUTO",
}


def store_weapons():
    weapons = []
    for line in (ROOT / "advanced_combat_training" / "mod" / "supply_drops" / "weapons.txt").read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("//") or line.startswith("#"):
            continue
        f = [x.strip() for x in line.split("|")]
        if len(f) < 6:
            continue
        weapons.append({"ref": f[0].lower(), "name": f[1], "category": f[2].lower(), "image": f[4], "stats": f[5].split()})
    return weapons


def build_store(rawfiles: pathlib.Path):
    weapons = store_weapons()
    mod = ROOT / "advanced_combat_training" / "mod"

    # statstable: a weapon row is index,id,class,name,ref,,image,description,,,,attachments x11,accuracy..mobility
    table = (rawfiles / "mp" / "statstable.csv").read_text().splitlines()
    table = [row for row in table if row.split(",")[4:5] not in ([w["ref"]] for w in weapons)]
    used = {int(r.split(",")[0]) for r in table if r.split(",")[0].isdigit()}
    index = max(used) + 1
    for w in weapons:
        row = [str(index), str(3000 + index), CATEGORY_CLASS[w["category"]], "WEAPON_" + w["ref"].upper(), w["ref"], "",
               w["image"], CATEGORY_DESC[w["category"]], "", "", ""] + [""] * 11 + (w["stats"] + ["50"] * 5)[:5]
        table.append(",".join(row))
        index += 1
    (mod / "mp").mkdir(exist_ok=True)
    (mod / "mp" / "statstable.csv").write_text("\n".join(table) + "\n", newline="\n")

    unlocks = (rawfiles / "mp" / "unlocktable.csv").read_text().splitlines()
    unlocks = [row for row in unlocks if row.split(",")[0] not in {w["ref"] for w in weapons}]
    for w in weapons:
        unlocks.append(f"{w['ref']},weapon,0,,,,,,,,,,")
    (mod / "mp" / "unlocktable.csv").write_text("\n".join(unlocks) + "\n", newline="\n")

    # The STORE WEAPONS popup, from IW4x's assault rifles one
    popup = (rawfiles / "ui_mp" / "popup_cac_assault_primary.menu").read_text()
    popup = popup.replace("popup_cac_assault_primary", "popup_cac_store_primary")
    popup = re.sub(r"#define ITEMNUM \d+", f"#define ITEMNUM {max(1, len(weapons))}", popup)
    popup = re.sub(r"rect 0 0 854 \d+ 1 1", f"rect 0 0 854 {4 + max(1, len(weapons)) * 20} 1 1", popup, count=1)
    first = weapons[0]["ref"] if weapons else "none"
    popup = re.sub(r'setfocus "cac_weapon_[a-z0-9]+";', f'setfocus "cac_weapon_{first}";', popup, count=1)
    lines, out, focus_done, rows_done = popup.split("\n"), [], False, False
    for line in lines:
        stripped = line.strip()
        indent = line[: len(line) - len(line.lstrip())]
        if stripped.startswith('CLASS_FOCUS("'):
            if not focus_done:
                out += [f'{indent}CLASS_FOCUS("{w["ref"]}")' for w in weapons]
                focus_done = True
            continue
        if stripped.startswith("CAC_PRIMARY_WEAPON("):
            if not rows_done:
                out += [f'{indent}SD_CAC_STORE_WEAPON({i},"{w["ref"]}")' for i, w in enumerate(weapons)]
                rows_done = True
            continue
        out.append(line)
    header = "// Generated by tools/build_sd_menus.py from supply_drops/weapons.txt: Create a Class, STORE WEAPONS.\n"
    (OUT / "popup_cac_store_primary.menu").write_text(header + "\n".join(out), newline="\n")
    print(f"store: {len(weapons)} weapons (statstable, unlocktable, popup_cac_store_primary)")


if __name__ == "__main__":
    sys.exit(main())
